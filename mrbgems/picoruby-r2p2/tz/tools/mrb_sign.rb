#!/usr/bin/env ruby
# frozen_string_literal: true

# mrb_sign.rb — host-side signer for sg_verify_mrb packages.
#
# Envelope format: ../include/r2p2_mrb_envelope.h (this file mirrors those
# constants — keep them in sync).
#
#   keygen  <key.pem>                     generate a P-256 signing keypair
#   pubkey  <key.pem> <mrb_pubkey.h>      emit the monitor's pubkey header
#   sign    <key.pem> <in.mrb> <out.mrbx> [version]   wrap + sign (default 0)
#   verify  <key.pem> <pkg.mrbx>          host-side round-trip check
#   selftest-header <key.pem> <out.h>     emit ../ns/tz_selftest_pkgs.h
#                                         (signed v3 + v1 packages for the
#                                         on-target TZ.selftest)
#
# The signature is ECDSA P-256, raw r||s (32+32 bytes, big-endian), over
# SHA-256(domain || header || payload).

require "openssl"

MAGIC   = 0x3142524d # "MRB1" LE
FMT     = 1
SCHEME  = 1          # ECDSA-P256-SHA256
SIG_LEN = 64
DOMAIN  = "R2P2-mrb-sig-v1\x00" # exactly 16 bytes
ROLLBACK_CAPACITY = 64 * 24     # OTP thermometer rows, keystore.c

raise "domain must be 16 bytes" unless DOMAIN.bytesize == 16

def header(payload_len, version)
  [MAGIC, FMT, SCHEME, 16, payload_len, version].pack("L<CCS<L<L<")
end

def digest(hdr, payload)
  OpenSSL::Digest::SHA256.digest(DOMAIN + hdr + payload)
end

def raw_sig_from_der(der)
  r, s = OpenSSL::ASN1.decode(der).value.map { |x| x.value.to_i }
  [r, s].map { |n| [n.to_s(16).rjust(64, "0")].pack("H*") }.join
end

def der_from_raw_sig(raw)
  r, s = raw[0, 32], raw[32, 32]
  OpenSSL::ASN1::Sequence.new(
    [r, s].map { |h| OpenSSL::ASN1::Integer.new(OpenSSL::BN.new(h.unpack1("H*"), 16)) }
  ).to_der
end

def pubkey_xy(key)
  point = key.public_key.to_octet_string(:uncompressed) # 0x04 || X || Y
  raise "unexpected point encoding" unless point.bytesize == 65 && point.getbyte(0) == 4
  point[1, 64]
end

case ARGV[0]
when "keygen"
  path = ARGV.fetch(1)
  key = OpenSSL::PKey::EC.generate("prime256v1")
  File.write(path, key.to_pem)
  File.chmod(0o600, path)
  puts "wrote #{path} (P-256). Regenerate mrb_pubkey.h with: #{$0} pubkey #{path} <out.h>"

when "pubkey"
  key = OpenSSL::PKey::EC.new(File.read(ARGV.fetch(1)))
  xy = pubkey_xy(key).bytes
  name = File.basename(ARGV.fetch(1))
  rows = xy.each_slice(12).map { |s| "    " + s.map { |b| format("0x%02x,", b) }.join(" ") }
  File.write(ARGV.fetch(2), <<~HEADER)
    /* mrb_pubkey.h — sg_verify_mrb verification key (X||Y, big-endian).
     * GENERATED by tz/tools/mrb_sign.rb pubkey from #{name} — do not edit.
     * A "dev" key name means the private half is committed to the repo for
     * development convenience: it authenticates NOTHING. Generate a fresh
     * keypair (kept off-repo) before enabling secure boot for real. */

    #ifndef MRB_PUBKEY_H
    #define MRB_PUBKEY_H

    #include <stdint.h>

    static const uint8_t r2p2_mrb_pubkey[64] = {
    #{rows.join("\n")}
    };

    #endif /* MRB_PUBKEY_H */
  HEADER
  puts "wrote #{ARGV[2]}"

when "sign"
  key = OpenSSL::PKey::EC.new(File.read(ARGV.fetch(1)))
  payload = File.binread(ARGV.fetch(2))
  version = Integer(ARGV[4] || 0)
  raise "version #{version} exceeds rollback capacity #{ROLLBACK_CAPACITY}" if version > ROLLBACK_CAPACITY

  hdr = header(payload.bytesize, version)
  sig = raw_sig_from_der(key.dsa_sign_asn1(digest(hdr, payload)))
  File.binwrite(ARGV.fetch(3), hdr + payload + sig)
  puts "wrote #{ARGV[3]}: #{payload.bytesize}B payload, version #{version}"

when "verify"
  key = OpenSSL::PKey::EC.new(File.read(ARGV.fetch(1)))
  pkg = File.binread(ARGV.fetch(2))
  hdr = pkg[0, 16]
  magic, fmt, scheme, hlen, plen, version = hdr.unpack("L<CCS<L<L<")
  raise "bad magic" unless magic == MAGIC
  raise "bad fmt/scheme/hlen" unless fmt == FMT && scheme == SCHEME && hlen == 16
  raise "bad length" unless pkg.bytesize == 16 + plen + SIG_LEN
  payload = pkg[16, plen]
  ok = key.dsa_verify_asn1(digest(hdr, payload), der_from_raw_sig(pkg[-SIG_LEN..]))
  puts "signature #{ok ? 'OK' : 'FAILED'}, version #{version}"
  exit(ok ? 0 : 1)

when "selftest-header"
  key = OpenSSL::PKey::EC.new(File.read(ARGV.fetch(1)))
  pkg = lambda do |version|
    payload = "R2P2 TZ selftest package v#{version}\n"
    hdr = header(payload.bytesize, version)
    hdr + payload + raw_sig_from_der(key.dsa_sign_asn1(digest(hdr, payload)))
  end
  carray = lambda do |name, bytes|
    rows = bytes.bytes.each_slice(12).map { |s| "    " + s.map { |b| format("0x%02x,", b) }.join(" ") }
    "static const uint8_t #{name}[#{bytes.bytesize}] = {\n#{rows.join("\n")}\n};\n"
  end
  File.write(ARGV.fetch(2), <<~HEADER)
    /* tz_selftest_pkgs.h — signed packages embedded in the on-target
     * TZ.selftest (tz_selftest.c). GENERATED — regenerate after changing
     * the envelope format or the signing key:
     *   tools/mrb_sign.rb selftest-header tools/mrb_signing_dev.pem \\
     *       ns/tz_selftest_pkgs.h */

    #include <stdint.h>

    /* version 3: verifies OK, advances the rollback shadow to 3 */
    #{carray.call('tz_pkg_v3', pkg.call(3))}
    /* version 1: rejected as rollback once v3 has been seen this boot */
    #{carray.call('tz_pkg_v1', pkg.call(1))}
  HEADER
  puts "wrote #{ARGV[2]}"

else
  warn "usage: #{$0} keygen|pubkey|sign|verify|selftest-header ... (see file header)"
  exit 2
end
